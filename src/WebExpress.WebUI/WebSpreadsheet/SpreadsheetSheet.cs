using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text.Json.Nodes;

namespace WebExpress.WebUI.WebSpreadsheet
{
    /// <summary>
    /// One sheet of a workbook, for building workbooks on the server and for reading posted ones.
    /// </summary>
    /// <remarks>
    /// Cells are kept by A1 name, the form the JSON uses, so a sheet costs only its filled cells.
    /// The sheet grows when a cell beyond its size is set, so callers never size it up front.
    /// </remarks>
    public sealed class SpreadsheetSheet
    {
        private readonly Dictionary<(int Row, int Column), SpreadsheetCell> _cells = [];

        /// <summary>
        /// Gets or sets the stable id; generated by the client when empty.
        /// </summary>
        public string Id { get; set; }

        /// <summary>
        /// Gets or sets the name shown on the tab.
        /// </summary>
        public string Name { get; set; }

        /// <summary>
        /// Gets or sets the number of rows.
        /// </summary>
        public int RowCount { get; set; } = 1000;

        /// <summary>
        /// Gets or sets the number of columns.
        /// </summary>
        public int ColumnCount { get; set; } = 26;

        /// <summary>
        /// Gets or sets the number of rows frozen at the top.
        /// </summary>
        public int FrozenRows { get; set; }

        /// <summary>
        /// Gets or sets the number of columns frozen at the left.
        /// </summary>
        public int FrozenColumns { get; set; }

        /// <summary>
        /// Gets the merged ranges in A1 notation, such as "A1:C1".
        /// </summary>
        public IList<string> Merges { get; } = [];

        /// <summary>
        /// Gets the heights of rows in pixels at 100 %, by zero-based row.
        /// </summary>
        public IDictionary<int, int> RowHeights { get; } = new Dictionary<int, int>();

        /// <summary>
        /// Gets the widths of columns in pixels at 100 %, by zero-based column.
        /// </summary>
        public IDictionary<int, int> ColumnWidths { get; } = new Dictionary<int, int>();

        /// <summary>
        /// Gets the styles of whole columns, by zero-based column.
        /// </summary>
        public IDictionary<int, SpreadsheetStyle> ColumnStyles { get; } = new Dictionary<int, SpreadsheetStyle>();

        /// <summary>
        /// Gets the styles of whole rows, by zero-based row.
        /// </summary>
        public IDictionary<int, SpreadsheetStyle> RowStyles { get; } = new Dictionary<int, SpreadsheetStyle>();

        /// <summary>
        /// Gets or sets the color of the sheet tab.
        /// </summary>
        public string TabColor { get; set; }

        /// <summary>
        /// Gets or sets whether gridlines are shown.
        /// </summary>
        public bool Gridlines { get; set; } = true;

        /// <summary>
        /// Gets the filled cells, by A1 name, in row-major order.
        /// </summary>
        public IReadOnlyDictionary<string, SpreadsheetCell> Cells => _cells
            .OrderBy(x => x.Key.Row).ThenBy(x => x.Key.Column)
            .ToDictionary(x => SpreadsheetAddress.CellName(x.Key.Row, x.Key.Column), x => x.Value);

        /// <summary>
        /// Initializes a new instance of the class.
        /// </summary>
        /// <param name="name">The name.</param>
        public SpreadsheetSheet(string name)
        {
            Name = name;
        }

        /// <summary>
        /// Gets or sets a cell by its A1 name; null clears it.
        /// </summary>
        /// <param name="reference">The A1 name.</param>
        /// <returns>The cell, or null.</returns>
        public SpreadsheetCell this[string reference]
        {
            get => GetCell(Parse(reference));
            set => SetCell(Parse(reference), value);
        }

        /// <summary>
        /// Returns a cell.
        /// </summary>
        /// <param name="row">The zero-based row.</param>
        /// <param name="column">The zero-based column.</param>
        /// <returns>The cell, or null.</returns>
        public SpreadsheetCell GetCell(int row, int column) => _cells.GetValueOrDefault((row, column));

        /// <summary>
        /// Stores or clears a cell, growing the sheet when needed.
        /// </summary>
        /// <param name="row">The zero-based row.</param>
        /// <param name="column">The zero-based column.</param>
        /// <param name="cell">The cell, or null to clear it.</param>
        /// <returns>The sheet, for chaining.</returns>
        public SpreadsheetSheet SetCell(int row, int column, SpreadsheetCell cell)
        {
            if (row < 0 || column < 0 || row >= SpreadsheetAddress.MaxRows || column >= SpreadsheetAddress.MaxColumns)
            {
                throw new ArgumentOutOfRangeException(nameof(row), "The cell lies outside the grid.");
            }

            if (cell is null)
            {
                _cells.Remove((row, column));
                return this;
            }

            _cells[(row, column)] = cell;
            RowCount = Math.Max(RowCount, row + 1);
            ColumnCount = Math.Max(ColumnCount, column + 1);

            return this;
        }

        /// <summary>
        /// Sets the value of a cell, keeping its format. A <see cref="DateTime"/> is stored as a
        /// serial number and gets a date format when the cell has none.
        /// </summary>
        /// <param name="reference">The A1 name.</param>
        /// <param name="value">The value: number, text, boolean, date or null.</param>
        /// <returns>The cell.</returns>
        public SpreadsheetCell SetValue(string reference, object value)
        {
            var position = Parse(reference);
            var cell = GetCell(position) ?? new SpreadsheetCell();

            cell.Formula = null;
            cell.Value = value is DateTime date ? SpreadsheetDate.ToSerial(date) : value;

            if (value is DateTime moment && string.IsNullOrEmpty(cell.Style?.NumberFormat))
            {
                cell.Style ??= new SpreadsheetStyle();
                cell.Style.NumberFormat = moment.TimeOfDay == TimeSpan.Zero ? "yyyy-mm-dd" : "yyyy-mm-dd hh:mm";
            }

            SetCell(position, cell);

            return cell;
        }

        /// <summary>
        /// Sets the formula of a cell, keeping its format.
        /// </summary>
        /// <param name="reference">The A1 name.</param>
        /// <param name="formula">The formula, with or without "=".</param>
        /// <returns>The cell.</returns>
        public SpreadsheetCell SetFormula(string reference, string formula)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(formula);

            var position = Parse(reference);
            var cell = GetCell(position) ?? new SpreadsheetCell();

            cell.Value = null;
            cell.Formula = formula.StartsWith('=') ? formula : "=" + formula;
            SetCell(position, cell);

            return cell;
        }

        /// <summary>
        /// Returns the value a reader sees: the client's result for a formula, the value otherwise.
        /// </summary>
        /// <param name="reference">The A1 name.</param>
        /// <returns>The value, or null.</returns>
        public object GetValue(string reference) => this[reference]?.EffectiveValue;

        /// <summary>
        /// Writes rows of values starting at a cell; a string starting with "=" becomes a formula.
        /// </summary>
        /// <param name="rows">The rows of values.</param>
        /// <param name="start">The top-left cell (default A1).</param>
        /// <returns>The sheet, for chaining.</returns>
        public SpreadsheetSheet SetData(IEnumerable<IEnumerable<object>> rows, string start = "A1")
        {
            var (row, column) = Parse(start);

            foreach (var values in rows ?? [])
            {
                var col = column;

                foreach (var value in values ?? [])
                {
                    var reference = SpreadsheetAddress.CellName(row, col++);

                    if (value is string text && text.Length > 1 && text.StartsWith('='))
                    {
                        SetFormula(reference, text);
                    }
                    else if (value is not null)
                    {
                        SetValue(reference, value);
                    }
                }

                row++;
            }

            return this;
        }

        /// <summary>
        /// Applies a style to every cell of a range, creating empty formatted cells where needed.
        /// </summary>
        /// <param name="range">The range, such as "A1:D1".</param>
        /// <param name="configure">Changes the style of each cell.</param>
        /// <returns>The sheet, for chaining.</returns>
        public SpreadsheetSheet Format(string range, Action<SpreadsheetStyle> configure)
        {
            ArgumentNullException.ThrowIfNull(configure);

            if (!SpreadsheetAddress.TryParseRange(range, out var first, out var last))
            {
                throw new ArgumentException("Invalid range: " + range, nameof(range));
            }

            for (var row = first.Row; row <= last.Row; row++)
            {
                for (var column = first.Column; column <= last.Column; column++)
                {
                    var cell = GetCell(row, column) ?? new SpreadsheetCell();
                    cell.Style ??= new SpreadsheetStyle();
                    configure(cell.Style);
                    SetCell(row, column, cell);
                }
            }

            return this;
        }

        /// <summary>
        /// Merges a range.
        /// </summary>
        /// <param name="range">The range, such as "A1:C1".</param>
        /// <returns>The sheet, for chaining.</returns>
        public SpreadsheetSheet Merge(string range)
        {
            if (!SpreadsheetAddress.TryParseRange(range, out var first, out var last) || first == last)
            {
                throw new ArgumentException("A merge needs a range of at least two cells.", nameof(range));
            }

            Merges.Add(SpreadsheetAddress.CellName(first.Row, first.Column) + ":" + SpreadsheetAddress.CellName(last.Row, last.Column));

            return this;
        }

        /// <summary>
        /// Freezes rows and columns.
        /// </summary>
        /// <param name="rows">The rows frozen at the top.</param>
        /// <param name="columns">The columns frozen at the left.</param>
        /// <returns>The sheet, for chaining.</returns>
        public SpreadsheetSheet Freeze(int rows, int columns = 0)
        {
            FrozenRows = Math.Max(0, rows);
            FrozenColumns = Math.Max(0, columns);

            return this;
        }

        /// <summary>
        /// Visits the filled cells in row-major order.
        /// </summary>
        /// <returns>The cells with their positions.</returns>
        public IEnumerable<(int Row, int Column, SpreadsheetCell Cell)> EnumerateCells()
        {
            return _cells.OrderBy(x => x.Key.Row).ThenBy(x => x.Key.Column).Select(x => (x.Key.Row, x.Key.Column, x.Value));
        }

        /// <summary>
        /// Writes the sheet as the JSON object the client reads.
        /// </summary>
        /// <param name="includeResults">Whether formula results are written.</param>
        /// <returns>The object.</returns>
        public JsonObject ToJson(bool includeResults = false)
        {
            var json = new JsonObject
            {
                ["name"] = Name,
                ["rowCount"] = RowCount,
                ["colCount"] = ColumnCount
            };

            if (!string.IsNullOrEmpty(Id))
            {
                json["id"] = Id;
            }

            var cells = new JsonObject();

            foreach (var (row, column, cell) in EnumerateCells())
            {
                if (cell.ToJson(includeResults) is { } node)
                {
                    cells[SpreadsheetAddress.CellName(row, column)] = node;
                }
            }

            json["cells"] = cells;

            var rows = Axis(RowHeights, RowStyles);
            var columns = Axis(ColumnWidths, ColumnStyles);

            if (rows.Count > 0) json["rows"] = rows;
            if (columns.Count > 0) json["cols"] = columns;
            if (Merges.Count > 0) json["merges"] = new JsonArray([.. Merges.Select(m => (JsonNode)m)]);
            if (FrozenRows > 0 || FrozenColumns > 0) json["frozen"] = new JsonObject { ["rows"] = FrozenRows, ["cols"] = FrozenColumns };

            var props = new JsonObject();

            if (SpreadsheetStyle.IsColor(TabColor)) props["tabColor"] = TabColor;
            if (!Gridlines) props["gridlines"] = false;
            if (props.Count > 0) json["props"] = props;

            return json;
        }

        /// <summary>
        /// Reads a sheet from its JSON form, validating everything on the way in. A missing or
        /// unusable name stays empty, because only the workbook knows which names are free.
        /// </summary>
        /// <param name="json">The sheet object.</param>
        /// <returns>The sheet.</returns>
        internal static SpreadsheetSheet FromJson(JsonObject json)
        {
            var sheet = new SpreadsheetSheet(json["name"] is JsonValue n && n.TryGetValue<string>(out var name) && !string.IsNullOrWhiteSpace(name) && name.Length <= 100 ? name.Trim() : null)
            {
                Id = json["id"] is JsonValue i && i.TryGetValue<string>(out var id) && id.Length <= 64 ? id : null,
                RowCount = Dimension(json["rowCount"], 1000, SpreadsheetAddress.MaxRows),
                ColumnCount = Dimension(json["colCount"], 26, SpreadsheetAddress.MaxColumns)
            };

            if (json["cells"] is JsonObject cells)
            {
                foreach (var (key, node) in cells)
                {
                    if (SpreadsheetAddress.TryParseCell(key, out var row, out var column) && SpreadsheetCell.FromJson(node) is { } cell)
                    {
                        sheet.SetCell(row, column, cell);
                    }
                }
            }

            if (json["data"] is JsonArray data)
            {
                sheet.SetData(data.Select(row => row is JsonArray values ? values.Select(v => SpreadsheetCell.FromNode(v)) : []));
            }

            ReadAxis(json["rows"], sheet.RowHeights, sheet.RowStyles);
            ReadAxis(json["cols"], sheet.ColumnWidths, sheet.ColumnStyles);

            if (json["merges"] is JsonArray merges)
            {
                foreach (var merge in merges.OfType<JsonValue>())
                {
                    if (merge.TryGetValue<string>(out var range) && SpreadsheetAddress.TryParseRange(range, out var first, out var last) && first != last)
                    {
                        sheet.Merges.Add(range);
                    }
                }
            }

            if (json["frozen"] is JsonObject frozen)
            {
                sheet.FrozenRows = Dimension(frozen["rows"], 0, sheet.RowCount - 1);
                sheet.FrozenColumns = Dimension(frozen["cols"], 0, sheet.ColumnCount - 1);
            }

            if (json["props"] is JsonObject props)
            {
                sheet.TabColor = props["tabColor"] is JsonValue c && c.TryGetValue<string>(out var color) && SpreadsheetStyle.IsColor(color) ? color : null;
                sheet.Gridlines = !(props["gridlines"] is JsonValue g && g.TryGetValue<bool>(out var gridlines) && !gridlines);
            }

            return sheet;
        }

        /// <summary>
        /// Writes the sizes and styles of rows or columns.
        /// </summary>
        /// <param name="sizes">The sizes.</param>
        /// <param name="styles">The styles.</param>
        /// <returns>The object by index.</returns>
        private static JsonObject Axis(IDictionary<int, int> sizes, IDictionary<int, SpreadsheetStyle> styles)
        {
            var json = new JsonObject();

            foreach (var index in sizes.Keys.Union(styles.Keys).Order())
            {
                var entry = new JsonObject();

                if (sizes.TryGetValue(index, out var size)) entry["size"] = Math.Clamp(size, 0, 2000);
                if (styles.TryGetValue(index, out var style) && style?.ToJson() is { } s) entry["s"] = s;
                if (entry.Count > 0) json[index.ToString(CultureInfo.InvariantCulture)] = entry;
            }

            return json;
        }

        /// <summary>
        /// Reads the sizes and styles of rows or columns.
        /// </summary>
        /// <param name="node">The object by index.</param>
        /// <param name="sizes">Receives the sizes.</param>
        /// <param name="styles">Receives the styles.</param>
        private static void ReadAxis(JsonNode node, IDictionary<int, int> sizes, IDictionary<int, SpreadsheetStyle> styles)
        {
            if (node is not JsonObject json)
            {
                return;
            }

            foreach (var (key, value) in json)
            {
                if (!int.TryParse(key, NumberStyles.None, CultureInfo.InvariantCulture, out var index) || value is not JsonObject entry)
                {
                    continue;
                }

                if (entry["size"] is JsonValue s && s.TryGetValue<double>(out var size) && size >= 0)
                {
                    sizes[index] = (int)Math.Min(2000, Math.Round(size));
                }

                if (SpreadsheetStyle.FromJson(entry["s"]) is { } style)
                {
                    styles[index] = style;
                }
            }
        }

        /// <summary>
        /// Reads a dimension.
        /// </summary>
        /// <param name="node">The value.</param>
        /// <param name="fallback">The value for a missing or invalid one.</param>
        /// <param name="max">The largest allowed value.</param>
        /// <returns>The dimension.</returns>
        private static int Dimension(JsonNode node, int fallback, int max)
        {
            return node is JsonValue v && v.TryGetValue<double>(out var d) && d >= 0 && d == Math.Floor(d) ? (int)Math.Min(d, max) : fallback;
        }

        /// <summary>
        /// Reads an A1 name or throws.
        /// </summary>
        /// <param name="reference">The name.</param>
        /// <returns>The position.</returns>
        private static (int Row, int Column) Parse(string reference)
        {
            return SpreadsheetAddress.TryParseCell(reference, out var row, out var column)
                ? (row, column)
                : throw new ArgumentException("Invalid cell reference: " + reference, nameof(reference));
        }

        /// <summary>
        /// Returns a cell by position.
        /// </summary>
        /// <param name="position">The position.</param>
        /// <returns>The cell, or null.</returns>
        private SpreadsheetCell GetCell((int Row, int Column) position) => GetCell(position.Row, position.Column);

        /// <summary>
        /// Stores a cell by position.
        /// </summary>
        /// <param name="position">The position.</param>
        /// <param name="cell">The cell.</param>
        private void SetCell((int Row, int Column) position, SpreadsheetCell cell) => SetCell(position.Row, position.Column, cell);
    }
}
