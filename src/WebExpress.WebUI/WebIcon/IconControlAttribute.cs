namespace WebExpress.WebUI.WebIcon
{
    /// <summary>
    /// Represents an icon for the attribute control, drawn as a chip split into a label and a value.
    /// </summary>
    public class IconControlAttribute : Icon
    {
        /// <summary>
        /// Returns the symbolic name the active icon set resolves to a css class.
        /// </summary>
        public override string Symbol => "control-attribute";
    }
}
